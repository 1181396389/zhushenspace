def kf(frames, ease="easeInOutSine"):
    out = {}
    for t, v in frames:
        e = ease
        if isinstance(v, tuple):
            v, e = v
        out[f"{t:.2f}".rstrip("0").rstrip(".") if t else "0.0"] = {"vector": v, "easing": e}
    return out

def anim(length, bones, loop=False):
    b = {}
    for name, chans in bones.items():
        b[name] = {ch: kf(frames) for ch, frames in chans.items()}
    return {"loop": loop, "animation_length": length, "bones": b}

def R(*frames):
    return {"rotation": list(frames)}

def mirror(v):  # 右臂 → 左臂
    return [v[0], -v[1], -v[2]]

def arms(frames_r, frames_l):
    return {"right_arm": {"rotation": frames_r}, "left_arm": {"rotation": frames_l}}

